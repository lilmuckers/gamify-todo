import type { HeroId } from '@quest/shared';

/**
 * Player characters. Original pixel art as character maps (see pixels.ts); the
 * digits are per-hero colour slots: 1 hair, 2 hair shade, 3 skin, 4 skin shade,
 * 5 top, 6 top accent, 7 bottoms, 8 bottoms shade, 9 shoes, 0 shoe accent.
 * 'classic' uses the original hero sprites in pixels.ts. Every hero also needs
 * dialogue portraits (portraits.ts) and lines (game/junk-lines.ts); tests check.
 */
export type HeroFrame = 'stand' | 'walk' | 'jump';

export interface HeroDef {
  label: string;
  description: string;
  /** How the hero talks, in a few words (SPEC §18.3). Shown on the hero's profile. */
  voice: string;
  /** A one- or two-sentence bio in the hero's voice: personality and style, never background or identity. */
  bio: string;
  /** A signature line in the hero's voice. */
  quote: string;
  colors?: Record<string, string>;
  frames?: Record<HeroFrame, string[]>;
}

/**
 * Walk and jump frames from a standing frame drawn on the common body: arms on
 * rows 10-11 swing out, legs (rows 13-15) stride or tuck. Leg and shoe colours
 * are copied from the standing pose, so stripes and checks carry over.
 */
function poses(stand: string[]): Record<HeroFrame, string[]> {
  const [r10, r11, , r13, r14] = stand.slice(10);
  const leg = r13.slice(5, 7);
  const shoe = r14.slice(4, 7);
  const top = stand.slice(0, 10);
  return {
    stand,
    walk: [...top, `${r10.slice(0, 12)}k3k.`, `${r11.slice(0, 11)}kk...`, stand[12], `...k${leg}k..k${leg}kk..`, `..k${shoe}k...k${shoe}k.`, '..kkkk.....kkkk.'],
    jump: [...top, `${r11.slice(1)}.`, `${r10.slice(0, 2)}k${r10.slice(3, 13)}k${r10.slice(14)}`, stand[12], `...k${leg}k..k${leg}k...`, `..k${shoe}k..k${shoe}k..`, '..kkkk....kkkk..'],
  };
}

